-- Esquema relacional de referencia para el modelo JPA de Indra Retail.
-- La aplicacion actual usa Hibernate con ddl-auto=create-drop; este archivo
-- documenta el esquema y no se ejecuta automaticamente con ese ajuste.

CREATE TABLE customers (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(255) NOT NULL,
	email VARCHAR(255) NOT NULL UNIQUE,
	created_at TIMESTAMP NOT NULL,
	street VARCHAR(200),
	city VARCHAR(200),
	state VARCHAR(100),
	zip_code VARCHAR(100)
);

CREATE TABLE products (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(255) NOT NULL,
	price DECIMAL(19, 2) NOT NULL,
	stock INTEGER NOT NULL,
	version BIGINT NOT NULL
);

CREATE TABLE orders (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	status VARCHAR(255) NOT NULL,
	created_at TIMESTAMP NOT NULL,
	customer_id BIGINT NOT NULL,
	CONSTRAINT ck_orders_status
		CHECK (status IN ('PENDING', 'CONFIRMED', 'SHIPPED')),
	CONSTRAINT fk_orders_customer
		FOREIGN KEY (customer_id) REFERENCES customers (id)
);

CREATE TABLE order_items (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	quantity INTEGER NOT NULL,
	unit_price DECIMAL(19, 2) NOT NULL,
	order_id BIGINT NOT NULL,
	product_id BIGINT NOT NULL,
	CONSTRAINT fk_order_items_order
		FOREIGN KEY (order_id) REFERENCES orders (id),
	CONSTRAINT fk_order_items_product
		FOREIGN KEY (product_id) REFERENCES products (id)
);

-- Decisiones de relaciones y cascada:
-- * Order -> Customer: LAZY y sin cascada; el pedido referencia al cliente,
--   pero no es propietario de su ciclo de vida.
-- * Order -> OrderItem: LAZY con PERSIST y MERGE en JPA. orphanRemoval=true
--   elimina el item desde el ORM al quitarlo de la coleccion del pedido.
-- * OrderItem -> Product: LAZY y sin cascada; borrar un item no debe borrar
--   el producto compartido o catalogado independientemente.
-- Las FK no usan ON DELETE CASCADE: los borrados en cascada descritos arriba
-- son decisiones del mapeo JPA, no reglas de borrado indiscriminado en SQL.
